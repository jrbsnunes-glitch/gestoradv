'use client';

import { useEffect } from 'react';
import { useRouter } from 'next/navigation';
import Link from 'next/link';
import { usePathname } from 'next/navigation';
import { useAuthStore } from '@/store/auth';
import { cn } from '@/lib/utils';

const navigation = [
  { name: 'Dashboard', href: '/dashboard', icon: LayoutDashboardIcon },
  { name: 'Processos', href: '/dashboard/processos', icon: FolderIcon },
  { name: 'Tarefas', href: '/dashboard/tarefas', icon: CheckSquareIcon },
  { name: 'Clientes', href: '/dashboard/clientes', icon: UsersIcon },
  { name: 'Advogados', href: '/dashboard/advogados', icon: BriefcaseIcon },
  { name: 'Financeiro', href: '/dashboard/financeiro', icon: DollarIcon },
  { name: 'Agenda', href: '/dashboard/agenda', icon: CalendarIcon },
  { name: 'Relatórios', href: '/dashboard/relatorios', icon: BarChartIcon },
  { name: 'Documentos', href: '/dashboard/documentos', icon: FileIcon },
  { name: 'Atendimentos', href: '/dashboard/chatbot', icon: InboxIcon },
  { name: 'Escritório', href: '/dashboard/escritorio', icon: BuildingIcon },
];

export default function DashboardLayout({ children }: { children: React.ReactNode }) {
  const router = useRouter();
  const pathname = usePathname();
  const { isAuthenticated, user, logout, hydrate } = useAuthStore();

  useEffect(() => {
    hydrate();
  }, [hydrate]);

  useEffect(() => {
    const token = localStorage.getItem('access_token');
    if (!token) {
      router.push('/');
    }
  }, [isAuthenticated, router]);

  return (
    <div className="flex h-screen overflow-hidden">
      <aside className="hidden w-64 flex-shrink-0 border-r border-border bg-sidebar lg:flex lg:flex-col">
        <div className="flex h-16 items-center gap-2.5 border-b border-border px-6">
          <img src="/logo.png" alt="GestorAdv" className="h-8 w-8 rounded-lg object-contain" />
          <span className="text-lg font-bold text-foreground">GestorAdv</span>
        </div>

        <nav className="flex-1 space-y-1 px-3 py-4">
          {navigation.map((item) => {
            const isActive = pathname === item.href;
            return (
              <Link
                key={item.name}
                href={item.href}
                className={cn(
                  'flex items-center gap-3 rounded-lg px-3 py-2.5 text-sm font-medium transition',
                  isActive
                    ? 'bg-primary/10 text-sidebar-active'
                    : 'text-sidebar-foreground hover:bg-secondary',
                )}
              >
                <item.icon className="h-5 w-5" />
                {item.name}
              </Link>
            );
          })}
        </nav>

        <div className="border-t border-border p-4">
          <div className="mb-3 flex items-center gap-3">
            <div className="flex h-9 w-9 items-center justify-center rounded-full bg-primary/10 text-sm font-semibold text-primary">
              {user?.email?.[0]?.toUpperCase() || 'U'}
            </div>
            <div className="min-w-0 flex-1">
              <p className="truncate text-sm font-medium text-foreground">{user?.email}</p>
              <p className="text-xs text-muted-foreground">{user?.role}</p>
            </div>
          </div>
          <button
            onClick={() => { logout(); router.push('/'); }}
            className="w-full rounded-lg border border-border px-3 py-2 text-xs font-medium text-muted-foreground transition hover:bg-secondary hover:text-foreground"
          >
            Sair
          </button>
        </div>
      </aside>

      <main className="flex-1 overflow-y-auto bg-background">
        <div className="p-6 lg:p-8">{children}</div>
      </main>
    </div>
  );
}

